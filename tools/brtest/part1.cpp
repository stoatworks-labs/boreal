/**
    brtest -- render Boreal offline, and measure what its sky is doing.

    It drives the REAL plugin class, through the same ProcessOpenGL a host
    calls, on a synthetic 60 fps clock, in a headless CGL context. Physics
    checks run against the CPU engine and the CPU reference tables, in km, s
    and nm; the optical checks read what the shipped shaders produced.

        brtest --out /tmp/sky.png        the source, the defaults
        brtest --over --out /tmp/o.png   the Over effect on the harness's card
        brtest --list                    every parameter and its default
        brtest --film N                  N frames, raw RGBA on stdout
        brtest --pipe                    raw frames in (Over), raw frames out

    `--script` is the fleet's cue format: `frame  Parameter Name  value` lines,
    held before the first key and after the last, linearly interpolated
    between. A button press is three keys (0, 1, 0).

    The claims, one flag each -- see README "Building and testing".
*/

